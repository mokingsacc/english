// The map for agents (ported from practice-hub): writes docs/agent-map.md between its markers, generated from the code so
// it never drifts: every route with the file and function that handle it (a report's trace names its route), every
// connector tool with its file, then every source file with its first comment line. CLAUDE.md points at it.
//   node scripts/agent-map.mjs           write it (npm run map)
//   node scripts/agent-map.mjs --check   exit 1 when it is out of date (tests/worker/agent-map.test.mjs runs the same check)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const OUT = path.join(ROOT, 'docs/agent-map.md');
export const START = '<!-- agent-map:start (generated by scripts/agent-map.mjs; do not edit by hand) -->';
export const END = '<!-- agent-map:end -->';
const rel = p => path.relative(ROOT, p).split(path.sep).join('/');

function walk(dir, re = /\.(m?js)$/) {
  if (!fs.existsSync(dir)) return [];
  const out = [];
  for (const e of fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) { if (e.name !== 'node_modules' && !e.name.startsWith('.')) out.push(...walk(p, re)); } else if (re.test(e.name) && e.name !== '_worker.js') out.push(p);
  }
  return out;
}

/** A file's first comment line (a // line or the first line of a block comment), cut to 160 characters. */
export function firstComment(src) {
  for (const raw of String(src).split('\n').slice(0, 12)) {
    const line = raw.trim();
    if (!line || line.startsWith('#!')) continue;
    const m = /^\/\/\s?(.*)$/.exec(line) || /^\/\*+\s?(.*?)(\*\/)?$/.exec(line) || /^#\s?(.*)$/.exec(line);
    if (!m) return '';
    const t = m[1].trim();
    if (t) return t.length > 160 ? `${t.slice(0, 159)}…` : t;
  }
  return '';
}

/** function -> file, over every module under src/worker (its exports and its routes' handlers). */
async function owners() {
  const map = new Map();
  for (const f of walk(path.join(ROOT, 'src/worker'))) {
    const mod = await import(pathToFileURL(f).href);
    for (const v of Object.values(mod)) {
      if (typeof v === 'function' && !map.has(v)) map.set(v, rel(f));
      if (v && typeof v === 'object' && !Array.isArray(v) && !map.has(v)) map.set(v, rel(f));
    }
    for (const r of Array.isArray(mod.routes) ? mod.routes : []) if (typeof r.handler === 'function') map.set(r.handler, rel(f));
  }
  return map;
}

export async function generated() {
  const { routeTable } = await import(pathToFileURL(path.join(ROOT, 'src/worker/routes.js')).href);
  const { TOOLS } = await import(pathToFileURL(path.join(ROOT, 'src/worker/mcp/registry.js')).href);
  const own = await owners();
  const lines = [START, '', '## Routes: the handler behind each one', '',
    'A problem report\'s trace names its route (`route` in the bugs tool\'s get); find it here. key: needs X-Key; none: open; token: the connector\'s address.', ''];
  const routes = routeTable().slice().sort((a, b) => a.pattern.localeCompare(b.pattern) || a.method.localeCompare(b.method));
  for (const r of routes) lines.push(`- \`${r.method} ${r.pattern}\` ${own.get(r.handler) || 'src/worker/index.js'} (${r.handler.name || 'inline'}) [${r.auth}]`);
  lines.push('', '## Connector tools (`mcp <tool>` in a trace)', '');
  for (const t of TOOLS) lines.push(`- \`${t.name}\` ${own.get(t) || 'src/worker/mcp/tools/'}`);
  for (const [dir, title, re] of [['src/worker', 'Worker files (src/worker)'], ['public/js', 'Page files (public/js; the engine is public/js/engine)'],
    ['scripts', 'Scripts (scripts)', /\.(m?js|sh)$/], ['migrations', 'Database migrations (migrations)', /\.sql$/]]) {
    lines.push('', `## ${title}`, '');
    for (const f of walk(path.join(ROOT, dir), re)) {
      const c = firstComment(fs.readFileSync(f, 'utf8').replace(/^--/gm, '//'));
      lines.push(`- ${rel(f)}${c ? `: ${c}` : ''}`);
    }
  }
  lines.push('', END);
  return lines.join('\n');
}

const HEAD = `# Agent map

First Pass's routes, connector tools and files, generated from the code by \`npm run map\` (a test fails when it is
stale, so run it after adding a file, a route or a tool). CLAUDE.md has the hand-written overview.

`;

export async function expected(current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '') {
  const gen = await generated();
  const a = current.indexOf(START), b = current.indexOf(END);
  if (a < 0 || b < 0) return `${HEAD}${gen}\n`;
  return current.slice(0, a) + gen + current.slice(b + END.length);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  const want = await expected(current);
  if (process.argv.includes('--check')) {
    if (want !== current) { console.error('docs/agent-map.md is out of date: run npm run map'); process.exit(1); }
    console.log('docs/agent-map.md is up to date');
  } else {
    fs.writeFileSync(OUT, want);
    console.log(`wrote ${rel(OUT)}`);
  }
}
